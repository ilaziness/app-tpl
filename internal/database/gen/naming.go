// isSensitiveColumn reports columns that must not appear in JSON output.
func isSensitiveColumn(name string) bool {
	switch strings.ToLower(name) {
	case "password", "passwd", "secret", "token", "access_token", "refresh_token", "api_key":
		return true
	default:
		return false
	}
}

// commonInitialisms maps lowercase SQL name segments to Go initialisms.
var commonInitialisms = map[string]string{
	"id":    "ID",
	"url":   "URL",
	"uri":   "URI",
	"api":   "API",
	"ip":    "IP",
	"uid":   "UID",
	"uuid":  "UUID",
	"http":  "HTTP",
	"https": "HTTPS",
	"json":  "JSON",
	"xml":   "XML",
	"sql":   "SQL",
	"pk":    "PK",
	"fk":    "FK",
	"pv":    "PV",
	"uv":    "UV",
}

// ToAlias generates a short alias from a snake_case table name. For tables
// with a single segment, the first two letters are used (e.g. actors -> ac,
// admins -> ad) to avoid collisions between tables that share the first letter.
// Multi-segment names use the first letter of each segment (e.g. site_stats_daily -> ssd).
func ToAlias(tableName string) string {
	parts := strings.Split(tableName, "_")
	if len(parts) == 0 {
		return "t"
	}
	if len(parts) == 1 {
		if len(tableName) >= 2 {
			return tableName[:2]
		}
		return tableName
	}
	var alias strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		alias.WriteRune(rune(p[0]))
	}
	if alias.Len() == 0 {
		return "t"
	}
	return alias.String()
}

// ToCamelCase converts snake_case to CamelCase (with common initialisms).
func ToCamelCase(s string) string {
	parts := strings.Split(s, "_")
	for i, part := range parts {
		lower := strings.ToLower(part)
		if repl, ok := commonInitialisms[lower]; ok {
			parts[i] = repl
			continue
		}
		parts[i] = titleCaser.String(part)
	}
	return strings.Join(parts, "")
}

func normalizeDriverLabel(driver string) string {
	switch driver {
	case "mysql":
		return "mysql"
	case "postgres", "postgresql":
		return "postgres"
	case "sqlite", "sqlite3":
		return "sqlite"
	default:
		if driver == "" {
			return "unknown"
		}
		return driver
	}
}

func buildJoinClause(sourceCols, targetCols string) string {
	src := splitCompositeColumns(sourceCols)
	tgt := splitCompositeColumns(targetCols)
	n := len(src)
	if len(tgt) < n {
		n = len(tgt)
	}
	parts := make([]string, 0, n)
	for i := 0; i < n; i++ {
		parts = append(parts, src[i]+"="+tgt[i])
	}
	return strings.Join(parts, ",")
}

func buildReverseJoinClause(sourceCols, targetCols string) string {
	// has-many / has-one on target: join targetPK=sourceFK → targetCols=sourceCols
	return buildJoinClause(targetCols, sourceCols)
}

func bindingTag(col Column, ft FieldType) string {
	var parts []string
	if !col.Nullable && !isSensitiveColumn(col.Name) && !(col.PrimaryKey && col.AutoIncrement) {
		parts = append(parts, "required")
	}
	if ft.Length > 0 && !ft.IsSet {
		parts = append(parts, fmt.Sprintf("max=%d", ft.Length))
	}
	if len(ft.EnumValues) > 0 && !ft.IsSet && enumValuesSafeForOneOf(ft.EnumValues) {
		parts = append(parts, "oneof="+strings.Join(ft.EnumValues, " "))
	}
	if len(parts) == 0 {
		return ""
	}
	return `binding:"` + strings.Join(parts, ",") + `"`
}

func enumValuesSafeForOneOf(values []string) bool {
	for _, v := range values {
		if strings.ContainsAny(v, " ,") {
			return false
		}
	}
	return len(values) > 0
}

// GenerateModelCode renders Go struct source for a database table.
func GenerateModelCode(opts GenerateOptions, modelName, tableName string, columns []Column, relations []Relation) string {
	driver := opts.Driver
	var sb strings.Builder

	sb.WriteString("// Code generated by app-tpl gen model. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Database driver: %s\n\n", normalizeDriverLabel(driver)))

	sb.WriteString(fmt.Sprintf("package %s\n\n", opts.PackageName))

	fieldTypes := make([]FieldType, len(columns))
	var hasJSON, hasTime bool
	var hasCreatedAt, hasUpdatedAt bool
	var createdAtNullable, updatedAtNullable bool
	for i, col := range columns {
		ft := MapColumn(driver, col)
		fieldTypes[i] = ft
		if strings.Contains(ft.GoType, "json.RawMessage") {
			hasJSON = true
		}
		if strings.Contains(ft.GoType, "time.Time") {
			hasTime = true
		}
		switch col.Name {
		case "created_at":
			hasCreatedAt = true
			createdAtNullable = col.Nullable
		case "updated_at":
			hasUpdatedAt = true
			updatedAtNullable = col.Nullable
		}
	}
	hasHook := hasCreatedAt || hasUpdatedAt

	sb.WriteString("import (\n")
	if hasHook {
		sb.WriteString("\t\"context\"\n")
	}
	if hasJSON {
		sb.WriteString("\t\"encoding/json\"\n")
	}
	if hasTime || hasHook {
		sb.WriteString("\t\"time\"\n")
	}
	if hasHook || hasJSON || hasTime {
		sb.WriteString("\n")
	}
	sb.WriteString("\t\"github.com/uptrace/bun\"\n")
	sb.WriteString(")\n\n")

	sb.WriteString(fmt.Sprintf("// %s represents the %s table.\n", modelName, tableName))
	sb.WriteString(fmt.Sprintf("type %s struct {\n", modelName))

	alias := ToAlias(tableName)
	if opts.Aliases != nil {
		if a, ok := opts.Aliases[tableName]; ok {
			alias = a
		}
	}
	sb.WriteString(fmt.Sprintf("\tbun.BaseModel `bun:\"table:%s,alias:%s\"`\n\n", tableName, alias))

	for i, col := range columns {
		ft := fieldTypes[i]
		commentParts := []string{}
		if c := SanitizeComment(col.Comment); c != "" {
			commentParts = append(commentParts, c)
		}
		if ft.RawComment != "" {
			commentParts = append(commentParts, "SQL type: "+ft.RawComment)
		}
		if len(commentParts) > 0 {
			sb.WriteString(fmt.Sprintf("\t// %s\n", strings.Join(commentParts, "; ")))
		}

		fieldName := ToCamelCase(col.Name)

		for _, relation := range relations {
			if relation.Type == RelationManyToMany || relation.SourceTable != tableName {
				continue
			}
			srcCols := splitCompositeColumns(relation.SourceColumn)
			if len(srcCols) == 0 || srcCols[0] != col.Name {
				continue
			}
			sb.WriteString(fmt.Sprintf("\t// Relation: %s -> %s(%s)\n",
				relation.SourceColumn, ToCamelCase(relation.TargetTable), relation.TargetColumn))
		}

		bunParts := []string{col.Name}
		if col.PrimaryKey {
			bunParts = append(bunParts, "pk")
			if col.AutoIncrement {
				bunParts = append(bunParts, "autoincrement")
			}
		}
		if !col.Nullable && !col.PrimaryKey {
			bunParts = append(bunParts, "notnull")
		}
		if col.Unique {
			if col.UniqueGroup != "" {
				bunParts = append(bunParts, "unique:"+col.UniqueGroup)
			} else {
				bunParts = append(bunParts, "unique")
			}
		}
		if col.Name == "deleted_at" && col.Nullable {
			bunParts = append(bunParts, "soft_delete", "nullzero")
		}
		if ft.BunType != "" {
			bunParts = append(bunParts, "type:"+ft.BunType)
		}
		if ft.Array {
			bunParts = append(bunParts, "array")
		}
		if def := NormalizeDefault(driver, col.Default, ft.GoType); def != "" {
			bunParts = append(bunParts, "default:"+def)
		}

		tags := []string{fmt.Sprintf(`bun:"%s"`, strings.Join(bunParts, ","))}
		if opts.JSONTags {
			jsonName := col.Name
			if isSensitiveColumn(col.Name) {
				jsonName = "-"
			}
			tags = append(tags, fmt.Sprintf(`json:"%s"`, jsonName))
		}
		if opts.ValidatorTags {
			if tag := bindingTag(col, ft); tag != "" {
				tags = append(tags, tag)
			}
		}

		sb.WriteString(fmt.Sprintf("\t%s %s `%s`\n", fieldName, ft.GoType, strings.Join(tags, " ")))
	}

	// Relation fields
	for _, relation := range relations {
		if relation.Type == RelationManyToMany {
			writeM2MFields(&sb, tableName, relation)
			continue
		}
		field, reverseField := relationFieldNames(relation)
		join := buildJoinClause(relation.SourceColumn, relation.TargetColumn)
		revJoin := buildReverseJoinClause(relation.SourceColumn, relation.TargetColumn)

		if relation.SourceTable == tableName {
			sb.WriteString(fmt.Sprintf("\t%s *%s `bun:\"rel:belongs-to,join:%s\" json:\"-\"`\n",
				field, ToCamelCase(relation.TargetTable), join))
		}
		if relation.TargetTable == tableName && !relation.SkipReverse {
			if relation.HasOne {
				sb.WriteString(fmt.Sprintf("\t%s *%s `bun:\"rel:has-one,join:%s\" json:\"-\"`\n",
					reverseField, ToCamelCase(relation.SourceTable), revJoin))
			} else {
				sb.WriteString(fmt.Sprintf("\t%s []*%s `bun:\"rel:has-many,join:%s\" json:\"-\"`\n",
					reverseField, ToCamelCase(relation.SourceTable), revJoin))
			}
		}
	}

	sb.WriteString("}\n")

	if hasHook {
		sb.WriteString("\n")
		sb.WriteString(fmt.Sprintf("var _ bun.BeforeAppendModelHook = (*%s)(nil)\n\n", modelName))
		sb.WriteString(fmt.Sprintf("func (m *%s) BeforeAppendModel(ctx context.Context, query bun.Query) error {\n", modelName))
		sb.WriteString("\tnow := time.Now()\n")
		sb.WriteString("\tswitch query.(type) {\n")
		if hasCreatedAt {
			sb.WriteString("\tcase *bun.InsertQuery:\n")
			if createdAtNullable {
				sb.WriteString("\t\tm.CreatedAt = &now\n")
			} else {
				sb.WriteString("\t\tm.CreatedAt = now\n")
			}
			if hasUpdatedAt {
				if updatedAtNullable {
					sb.WriteString("\t\tm.UpdatedAt = &now\n")
				} else {
					sb.WriteString("\t\tm.UpdatedAt = now\n")
				}
			}
		}
		if hasUpdatedAt {
			sb.WriteString("\tcase *bun.UpdateQuery:\n")
			if updatedAtNullable {
				sb.WriteString("\t\tm.UpdatedAt = &now\n")
			} else {
				sb.WriteString("\t\tm.UpdatedAt = now\n")
			}
		}
		sb.WriteString("\t}\n")
		sb.WriteString("\treturn nil\n")
		sb.WriteString("}\n")
	}

	return sb.String()
}

func writeM2MFields(sb *strings.Builder, tableName string, relation Relation) {
	field, reverseField := relationFieldNames(relation)
	if relation.SourceTable == tableName {
		sb.WriteString("\t// Register the join model with db.RegisterModel before using this m2m relation.\n")
		sb.WriteString(fmt.Sprintf("\t%s []*%s `bun:\"m2m:%s,join:%s\" json:\"-\"`\n",
			field, ToCamelCase(relation.TargetTable), relation.Through, relation.M2MJoin))
	}
	if relation.TargetTable == tableName {
		// Reverse join swaps field names in join clause.
		revJoin := swapM2MJoin(relation.M2MJoin)
		sb.WriteString("\t// Register the join model with db.RegisterModel before using this m2m relation.\n")
		sb.WriteString(fmt.Sprintf("\t%s []*%s `bun:\"m2m:%s,join:%s\" json:\"-\"`\n",
			reverseField, ToCamelCase(relation.SourceTable), relation.Through, revJoin))
	}
}

func swapM2MJoin(join string) string {
	parts := strings.SplitN(join, "=", 2)
	if len(parts) != 2 {
		return join
	}
	return parts[1] + "=" + parts[0]
}
